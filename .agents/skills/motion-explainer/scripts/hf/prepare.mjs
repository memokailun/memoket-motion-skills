#!/usr/bin/env node
const USAGE = `
prepare.mjs: get a HyperFrames project ready to lint, check and render without the network. Run it from the project
folder after npm install, and again after every copy change.

  node <SKILL_DIR>/scripts/hf/prepare.mjs [index.html more.html ...] [--no-vendor] [--no-fonts] [--no-timing]

  1. vendor   copies node_modules/gsap/dist/gsap.min.js to vendor/ (the init template loads GSAP from a CDN; the
              compiler may fetch or inline remote scripts and a render must not need the network). Add plugins with
              --plugins CustomEase,SplitText
  2. fonts    copies the OFL woff2 files named in fonts.config.json from node_modules/@fontsource* into fonts/ with
              each LICENSE, writes fonts/fonts.css with relative URLs and font-display: block (a frame is never
              captured with a fallback face), plus alias families (Geist Variable and Geist)
  3. timing   writes assets/timing.js (window.TIMING = timing.json; the composition cannot fetch at render time) and
              sets data-duration on the root composition to timing.duration
  4. inline   writes the @font-face rules each html needs INTO the html (<style id="hf-local-fonts">): the compiler
              only sees faces written in the html text; a family declared only in a linked css is fetched from
              Google Fonts at compile time and overrides the local files. Only slices whose unicode-range meets the
              characters used in the html and the local scripts it links (plus printable ASCII) are written
Default html: index.html. Cuts (make_cut.mjs) keep their duration; after prepare, regenerate them from index.html.
Never edit generated files by hand.
`
import fs from 'node:fs'
import path from 'node:path'
import { parseArgs, usage, fail, projectBase } from '../lib/page.mjs'

const A = parseArgs(process.argv.slice(2), ['no-vendor', 'no-fonts', 'no-timing'])
usage(USAGE, A)
const HTML = A._.length ? A._ : ['index.html']
const NM = path.join(projectBase(), 'node_modules')
if (!fs.existsSync(NM)) fail(`no node_modules in ${projectBase()}: run npm install in the project folder first`)

if (!A['no-vendor']) {
  fs.mkdirSync('vendor', { recursive: true })
  for (const name of ['gsap', ...(A.plugins ? A.plugins.split(',') : [])]) {
    const src = path.join(NM, 'gsap/dist', name + '.min.js')
    if (!fs.existsSync(src)) fail(`${src} not found (is gsap installed?)`)
    fs.copyFileSync(src, path.join('vendor', name + '.min.js'))
  }
  console.log('vendor: gsap copied to vendor/')
}

if (!A['no-fonts']) {
  if (!fs.existsSync('fonts.config.json')) fail('fonts.config.json missing (see the hyperframes template)')
  const SETS = JSON.parse(fs.readFileSync('fonts.config.json', 'utf8')).sets
  const faceRe = /@font-face\s*\{[^}]*\}/g
  const out = ['/* Generated by scripts/hf/prepare.mjs. Do not edit by hand. Fonts: SIL Open Font License 1.1 (LICENSE in each folder). */']
  let copied = 0
  fs.rmSync('fonts', { recursive: true, force: true })
  for (const set of SETS) {
    const pkgDir = path.join(NM, set.pkg), dest = path.join('fonts', set.dir)
    if (!fs.existsSync(pkgDir)) fail(`${set.pkg} is not installed (add it to package.json)`)
    fs.mkdirSync(dest, { recursive: true })
    for (const lic of ['LICENSE', 'LICENSE.txt', 'OFL.txt']) if (fs.existsSync(path.join(pkgDir, lic))) fs.copyFileSync(path.join(pkgDir, lic), path.join(dest, lic))
    for (const cssName of set.css) {
      const css = fs.readFileSync(path.join(pkgDir, cssName), 'utf8')
      for (const block of css.match(faceRe) || []) {
        const m = block.match(/url\(\.\/files\/([^)]+\.woff2)\)\s*format\('(woff2(?:-variations)?)'\)/)
        if (!m) continue
        if (!fs.existsSync(path.join(dest, m[1]))) { fs.copyFileSync(path.join(pkgDir, 'files', m[1]), path.join(dest, m[1])); copied++ }
        const fixed = block.replace(/font-display:\s*swap/, 'font-display: block').replace(/src:[^;]+;/, `src: url("./${set.dir}/${m[1]}") format("woff2");`)
        out.push(fixed)
        if (set.alias) out.push(fixed.replace(/font-family:\s*'[^']+'/, `font-family: '${set.alias}'`))
      }
    }
  }
  fs.writeFileSync('fonts/fonts.css', out.join('\n') + '\n')
  console.log(`fonts: ${copied} woff2 files copied, fonts/fonts.css written`)
}

if (!A['no-timing'] && fs.existsSync('timing.json')) {
  const T = JSON.parse(fs.readFileSync('timing.json', 'utf8'))
  fs.mkdirSync('assets', { recursive: true })
  fs.writeFileSync('assets/timing.js', '/* generated by scripts/hf/prepare.mjs from timing.json; do not edit */\nwindow.TIMING = ' + JSON.stringify(T) + ';\n')
  for (const f of HTML) {
    let html = fs.readFileSync(f, 'utf8')
    if (html.includes('window.__CUT')) continue        // a cut keeps its own (stretched) duration: regenerate it instead
    const re = /(<div id="root"[^>]*?data-duration=")([\d.]+)(")/
    if (re.test(html)) { html = html.replace(re, `$1${T.duration}$3`); fs.writeFileSync(f, html) }
  }
  console.log(`timing: assets/timing.js written, data-duration ${T.duration}`)
}

// ------------------------------------------------------------------ inline the faces each html needs
const css = fs.existsSync('fonts/fonts.css') ? fs.readFileSync('fonts/fonts.css', 'utf8') : fail('fonts/fonts.css missing: run without --no-fonts once')
const faces = css.match(/@font-face\s*\{[^}]*\}/g) || []
const parseRange = (block) => {
  const m = block.match(/unicode-range:\s*([^;}]+)/)
  if (!m) return [[0, 0x10ffff]]
  return m[1].split(',').map((s) => s.trim().replace(/^U\+/i, '')).map((tok) => {
    if (tok.includes('?')) return [parseInt(tok.replace(/\?/g, '0'), 16), parseInt(tok.replace(/\?/g, 'f'), 16)]
    const [a, b] = tok.split('-'); return [parseInt(a, 16), parseInt(b ?? a, 16)]
  })
}
const blockRe = /<style id="hf-local-fonts">[\s\S]*?<\/style>/
for (const file of HTML) {
  let html = fs.readFileSync(file, 'utf8')
  let scan = html.replace(blockRe, '')
  // strings in linked local scripts (captions, labels) need their slices too; vendor and fonts are skipped
  for (const m of html.matchAll(/<script[^>]+src="([^"]+)"/g)) {
    const p = path.join(path.dirname(file), m[1])
    if (/^(https?:)?\/\//.test(m[1]) || /(^|\/)(vendor|fonts)\//.test(m[1]) || !fs.existsSync(p)) continue
    scan += fs.readFileSync(p, 'utf8')
  }
  const used = new Set(); for (const ch of scan) used.add(ch.codePointAt(0))
  const hits = (ranges) => ranges.some(([a, b]) => (a <= 0x7e && 0x20 <= b) || [...used].some((c) => c >= a && c <= b))
  const rel = path.relative(path.dirname(path.resolve(file)), path.resolve('fonts')).split(path.sep).join('/') || '.'
  const picked = faces.filter((f) => hits(parseRange(f))).map((f) => f.replace(/url\("\.\/([^"]+)"\)/, `url("${rel.startsWith('.') ? rel : './' + rel}/$1")`))
  const block = `<style id="hf-local-fonts">\n/* generated by scripts/hf/prepare.mjs: ${picked.length} faces, do not edit by hand */\n${picked.join('\n')}\n</style>`
  html = blockRe.test(html) ? html.replace(blockRe, block) : html.replace(/<\/head>/i, `  ${block}\n  </head>`)
  fs.writeFileSync(file, html)
  console.log(`inline: ${file}: ${picked.length} @font-face rules (${used.size} distinct characters scanned)`)
}
